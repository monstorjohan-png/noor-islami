/** قنوات لوحة — نسخة أمينة، فالتعديل على الأصل لا يجوز */
export function paletteVars(id: PaletteId): PaletteVars {
  return { ...PALETTE_VARS[isPalette(id) ? id : DEFAULT_PALETTE] };
}

/** «11 18 32» ← «#0b1220» */
function toHex(channels: string): string {
  const parts = channels.split(' ').map((n) => Number(n));
  if (parts.length !== 3 || parts.some((n) => !Number.isInteger(n) || n < 0 || n > 255)) {
    return '#000000';
  }
  return `#${parts.map((n) => n.toString(16).padStart(2, '0')).join('')}`;
}

/**
 * يثبّت اللوحة على عنصر الجذر فيتبدّل لون التطبيق كله.
 * لوحة مجهول أو تخزين تالف ⇒ اللوحة الافتراضية، ولا رمي أبداً:
 * تبديل اللون زينة، وسقوط التطبيق بسببه عطل.
 */
export function applyPalette(id: PaletteId): void {
  if (typeof document === 'undefined') return;
  const safe = isPalette(id) ? id : DEFAULT_PALETTE;
  try {
    document.documentElement.dataset.palette = safe;
    // شريط الحالة في الجوال يتبع لون اللوحة وإلا بقي على لون اللوحة الأولى
    const meta = document.querySelector('meta[name="theme-color"]') as HTMLMetaElement | null;
    if (meta) meta.content = toHex(paletteVars(safe)['--ink-900']);
  } catch {
    /* لون الصفحة لا يسقط التطبيق */
  }
}
